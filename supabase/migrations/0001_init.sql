-- При создании заказа копируем шаблон в его чек-лист
create or replace function copy_checklist() returns trigger
language plpgsql as $$
begin
  insert into checklist_items (order_id, zone, title, sort)
  select new.id, zone, title, sort from checklist_templates where type = new.type;
  return new;
end $$;

create trigger orders_copy_checklist
after insert on orders for each row execute function copy_checklist();

-- ── Взятие заказа одним атомарным запросом ──────────────────
-- Пусто в ответе = заказ уже забрали или уровень клинера не подходит.
create or replace function take_order(p_order bigint, p_cleaner uuid)
returns setof orders
language plpgsql as $$
declare
  lvl cleaner_level;
begin
  select level into lvl from cleaners where id = p_cleaner and status = 'active';
  if lvl is null then
    return;
  end if;
  return query
    update orders
       set cleaner_id = p_cleaner, status = 'taken', taken_at = now()
     where id = p_order
       and status = 'open'
       and min_level <= lvl
       and scheduled_at > now()
    returning *;
end $$;

-- ── Рейтинг и уровень ───────────────────────────────────────
-- Рейтинг = средняя оценка клиентов за последние 20 заказов − штрафы, в пределах 1..5.
-- Уровень: standard после 5 заказов с рейтингом от 4,5; pro после 30 с рейтингом от 4,8.
create or replace function recalc_cleaner(p_cleaner uuid)
returns void
language plpgsql as $$
declare
  avg_rate numeric;
  done_cnt int;
  pen      numeric;
  new_rate numeric;
  cur_lvl  cleaner_level;
  new_lvl  cleaner_level;
begin
  select avg(client_rating) into avg_rate from (
    select client_rating from orders
     where cleaner_id = p_cleaner and client_rating is not null
     order by accepted_at desc nulls last
     limit 20
  ) t;

  select count(*) into done_cnt from orders
   where cleaner_id = p_cleaner and status in ('accepted', 'paid');

  select penalty, level into pen, cur_lvl from cleaners where id = p_cleaner;

  new_rate := greatest(1, least(5, coalesce(avg_rate, 5) - coalesce(pen, 0)));

  new_lvl := case
    when done_cnt >= 30 and new_rate >= 4.8 then 'pro'::cleaner_level
    when done_cnt >= 5  and new_rate >= 4.5 then 'standard'::cleaner_level
    else 'new'::cleaner_level
  end;

  update cleaners set rating = round(new_rate, 2), level = new_lvl where id = p_cleaner;
end $$;

