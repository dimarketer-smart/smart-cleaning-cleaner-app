create extension if not exists pgcrypto;

-- ── Справочники ─────────────────────────────────────────────
create type cleaner_level  as enum ('new', 'standard', 'pro');       -- порядок важен: сравнение new < standard < pro
create type cleaner_status as enum ('pending', 'active', 'blocked');
create type order_status   as enum ('open', 'taken', 'confirmed', 'on_way', 'onsite',
                                    'submitted', 'rework', 'accepted', 'paid', 'cancelled');

-- ── Люди ────────────────────────────────────────────────────
create table cleaners (
  id          uuid primary key default gen_random_uuid(),
  tg_id       bigint unique not null,
  name        text not null,
  phone       text,
  kaspi       text,                                   -- номер для выплат, если отличается от phone
  level       cleaner_level  not null default 'new',
  rating      numeric(3,2)   not null default 5.00,
  penalty     numeric(4,2)   not null default 0,      -- накопленные штрафы, вычитаются из рейтинга
  status      cleaner_status not null default 'pending',
  created_at  timestamptz not null default now()
);

create table clients (
  id          uuid primary key default gen_random_uuid(),
  tg_id       bigint unique,                          -- появляется, когда клиент нажал ссылку на бота
  name        text,
  phone       text,
  link_token  text unique not null default encode(gen_random_bytes(6), 'hex'),
  source      text,
  created_at  timestamptz not null default now()
);

-- ── Заказы ──────────────────────────────────────────────────
create table orders (
  id                bigint generated by default as identity (start with 1001) primary key,
  client_id         uuid references clients(id),
  cleaner_id        uuid references cleaners(id),
  type              text not null default 'wet',
  district          text not null,
  address           text not null,                    -- клинеру отдаётся только после взятия
  area_m2           int  not null check (area_m2 > 0),
  rooms             int,
  scheduled_at      timestamptz not null,
  price_client      int  not null check (price_client >= 0),
  payout_cleaner    int  not null check (payout_cleaner >= 0),
  min_level         cleaner_level not null default 'new',
  notes             text,
  status            order_status not null default 'open',
  taken_at          timestamptz,
  confirmed_at      timestamptz,
  on_way_at         timestamptz,
  onsite_at         timestamptz,
  onsite_lat        double precision,
  onsite_lng        double precision,
  submitted_at      timestamptz,
  accepted_at       timestamptz,
  paid_at           timestamptz,
  cleaner_comment   text,
  client_rating     int check (client_rating between 1 and 5),
  client_comment    text,
  -- флаги для cron, чтобы не слать одно и то же дважды
  reminded_confirm  boolean not null default false,
  reminded_2h       boolean not null default false,
  alerted_late      boolean not null default false,
  alerted_unclaimed boolean not null default false,
  created_at        timestamptz not null default now()
);
create index orders_status_idx   on orders (status, scheduled_at);
create index orders_cleaner_idx  on orders (cleaner_id, status);

create table checklist_templates (
  id     serial primary key,
  type   text not null,
  zone   text not null,
  title  text not null,
  sort   int  not null
);

create table checklist_items (
  id        bigint generated by default as identity primary key,
  order_id  bigint not null references orders(id) on delete cascade,
  zone      text not null,
  title     text not null,
  sort      int  not null,
  done      boolean not null default false,
  done_at   timestamptz
);
create index checklist_items_order_idx on checklist_items (order_id);

create table photos (
  id            bigint generated by default as identity primary key,
  order_id      bigint not null references orders(id) on delete cascade,
  zone          text not null,
  kind          text not null check (kind in ('before', 'after')),
  storage_path  text not null,
  created_at    timestamptz not null default now()
);
create index photos_order_idx on photos (order_id, kind);

-- Журнал смены статусов — для разбора споров
create table order_events (
  id           bigint generated by default as identity primary key,
  order_id     bigint not null references orders(id) on delete cascade,
  actor        text not null check (actor in ('cleaner', 'client', 'admin', 'system')),
  cleaner_id   uuid references cleaners(id),
  from_status  order_status,
  to_status    order_status not null,
  comment      text,
  created_at   timestamptz not null default now()
);
create index order_events_order_idx   on order_events (order_id);
create index order_events_cleaner_idx on order_events (cleaner_id, created_at);

create table payouts (
  id          bigint generated by default as identity primary key,
  cleaner_id  uuid not null references cleaners(id),
  order_id    bigint not null unique references orders(id),
  amount      int not null,
  status      text not null default 'pending' check (status in ('pending', 'paid')),
  paid_at     timestamptz,
  paid_by     bigint,                                -- tg_id админа
  created_at  timestamptz not null default now()
);

-- Копия переписки через бота
create table messages (
  id          bigint generated by default as identity primary key,
  order_id    bigint not null references orders(id) on delete cascade,
  sender      text not null check (sender in ('cleaner', 'client')),
  text        text not null,
  created_at  timestamptz not null default now()
);

-- Кто сейчас в каком «режиме» в боте: чат по заказу или ввод замечания
create table bot_sessions (
  tg_id       bigint primary key,
  mode        text not null check (mode in ('chat', 'complaint')),
  order_id    bigint not null references orders(id) on delete cascade,
  updated_at  timestamptz not null default now()
);

